// Copies everything from Supabase Storage into the Cloudflare R2 bucket and
// generates the SQL that rewrites the stored URLs in Postgres.
//
//   node scripts/migrate-to-r2.mjs          # dry run, copies nothing
//   node scripts/migrate-to-r2.mjs --apply  # actually upload to R2
//
// Nothing is deleted from Supabase, so the old public URLs keep working until
// you delete the buckets yourself.

import { createClient } from "@supabase/supabase-js";
import { PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { Readable } from "node:stream";
import { loadEnvFile } from "./load-env.mjs";

const BUCKETS = {
  "project-covers": "covers",
  "project-images": "images",
  "project-pdfs": "pdfs",
  "project-videos": "videos",
};

// table -> columns that hold a Supabase Storage public URL
const SQL_TARGETS = [
  ["public.categories", ["cover"]],
  ["public.projects", ["cover", "pdf_url"]],
  ["public.project_images", ["image_url"]],
  ["public.gallery_images", ["image_url"]],
  ["public.showcase_images", ["image_url", "thumbnail_url"]],
  ["public.certificates", ["file_url"]],
  ["public.cv_documents", ["file_url"]],
  ["public.clo3d_videos", ["video_url"]],
  ["public.about_cards", ["cover"]],
  ["public.page_videos", ["cover", "video_url"]],
  ["public.additional_work_videos", ["video_url"]],
  ["public.showcase_videos", ["video_url"]],
];

const SQL_FILE = "lib/supabase/migrations/015_r2_url_rewrite.sql";

const APPLY = process.argv.includes("--apply");

loadEnvFile();

function env(name) {
  const value = process.env[name];
  if (!value) throw new Error(`Missing environment variable: ${name}`);
  return value;
}

const supabaseUrl = env("NEXT_PUBLIC_SUPABASE_URL").replace(/\/+$/, "");
const supabase = createClient(
  supabaseUrl,
  env("NEXT_PUBLIC_SUPABASE_ANON_KEY"),
);

const r2 = new S3Client({
  region: "auto",
  endpoint: `https://${env("R2_ACCOUNT_ID")}.r2.cloudflarestorage.com`,
  credentials: {
    accessKeyId: env("R2_ACCESS_KEY_ID"),
    secretAccessKey: env("R2_SECRET_ACCESS_KEY"),
  },
});

const r2Bucket = process.env.R2_BUCKET || "portfolio-media";
const r2PublicUrl = env("R2_PUBLIC_URL").replace(/\/+$/, "");

async function walk(bucket, prefix = "") {
  const { data, error } = await supabase.storage
    .from(bucket)
    .list(prefix, { limit: 1000 });

  if (error) throw new Error(`${bucket}/${prefix}: ${error.message}`);

  const files = [];

  for (const entry of data ?? []) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;

    // Supabase returns folders with a null id.
    if (entry.id === null) {
      files.push(...(await walk(bucket, path)));
    } else {
      files.push(path);
    }
  }

  return files;
}

async function copyFile(bucket, prefix, path) {
  const publicUrl = `${supabaseUrl}/storage/v1/object/public/${bucket}/${path}`;
  const key = `${prefix}/${path}`;

  const response = await fetch(publicUrl);

  if (!response.ok) {
    throw new Error(`GET ${publicUrl} -> ${response.status}`);
  }

  const contentLength = Number(response.headers.get("content-length")) || undefined;

  await r2.send(
    new PutObjectCommand({
      Bucket: r2Bucket,
      Key: key,
      Body: Readable.fromWeb(response.body),
      ContentLength: contentLength,
      ContentType:
        response.headers.get("content-type") || "application/octet-stream",
      CacheControl: "3600",
    }),
  );
}

function escapeSql(value) {
  return value.replace(/'/g, "''");
}

function buildSql() {
  const statements = [];

  for (const [bucket, prefix] of Object.entries(BUCKETS)) {
    const oldBase = `${supabaseUrl}/storage/v1/object/public/${bucket}/`;
    const newBase = `${r2PublicUrl}/${prefix}/`;

    for (const [table, columns] of SQL_TARGETS) {
      for (const column of columns) {
        statements.push(
          `update ${table}\n` +
            `set ${column} = replace(${column}, '${escapeSql(oldBase)}', '${escapeSql(newBase)}')\n` +
            `where ${column} like '${escapeSql(oldBase)}%';`,
        );
      }
    }
  }

  // Profile settings keeps its URLs inside a jsonb blob.
  for (const [bucket, prefix] of Object.entries(BUCKETS)) {
    const oldBase = `${supabaseUrl}/storage/v1/object/public/${bucket}/`;
    const newBase = `${r2PublicUrl}/${prefix}/`;

    statements.push(
      `update public.profile_settings\n` +
        `set data = replace(data::text, '${escapeSql(oldBase)}', '${escapeSql(newBase)}')::jsonb\n` +
        `where data::text like '%${escapeSql(oldBase)}%';`,
    );
  }

  return `-- Generated by scripts/migrate-to-r2.mjs\n` +
    `-- Rewrites Supabase Storage URLs to their Cloudflare R2 equivalents.\n` +
    `-- Run in the Supabase SQL Editor AFTER the files have been copied to R2.\n\n` +
    `begin;\n\n${statements.join("\n\n")}\n\ncommit;\n`;
}

async function main() {
  console.log(`Mode: ${APPLY ? "APPLY (uploading to R2)" : "dry run"}`);
  console.log(`R2 bucket: ${r2Bucket}, public base: ${r2PublicUrl}\n`);

  let total = 0;
  let copied = 0;
  const failures = [];

  for (const [bucket, prefix] of Object.entries(BUCKETS)) {
    let files = [];

    try {
      files = await walk(bucket);
    } catch (error) {
      console.log(`  ${bucket}: ${error.message}`);
      failures.push(`${bucket}: ${error.message}`);
      continue;
    }

    console.log(`${bucket} -> ${prefix}/  (${files.length} files)`);
    total += files.length;

    for (const path of files) {
      if (!APPLY) {
        console.log(`  would copy ${path}`);
        continue;
      }

      try {
        await copyFile(bucket, prefix, path);
        copied += 1;
        console.log(`  copied ${path}`);
      } catch (error) {
        failures.push(`${bucket}/${path}: ${error.message}`);
        console.log(`  FAILED ${path}: ${error.message}`);
      }
    }
  }

  console.log(`\n${total} files found, ${copied} copied.`);

  const sql = buildSql();
  const { writeFile, mkdir } = await import("node:fs/promises");
  const { dirname } = await import("node:path");

  await mkdir(dirname(SQL_FILE), { recursive: true });
  await writeFile(SQL_FILE, sql, "utf8");

  console.log(`URL rewrite SQL written to ${SQL_FILE}`);

  if (failures.length > 0) {
    console.log(`\n${failures.length} problem(s):`);
    for (const failure of failures) console.log(`  - ${failure}`);
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
